#include "kc/security/Digest.h"
#include "kc/tools/FirmwareChecksum.h"

#include <QByteArray>
#include <QDir>
#include <QFile>
#include <QString>
#include <QTemporaryDir>

#include <iostream>

namespace {

int failures = 0;

void check(bool ok, const char* what)
{
    if (!ok) {
        std::cerr << "FAIL: " << what << '\n';
        ++failures;
    }
}

} // namespace

// 固件校验（移植自 TMFTool 的 MD5 / SHA-256 校验与「生成校验文件」）的纯逻辑回归。
// 摘要值用公开测试向量钉死：算错了就是「校验永远不通过」或「坏包被放过」。
int main()
{
    using kc::crypto::HashAlgo;
    using kc::tools::checksumFileName;
    using kc::tools::formatChecksumLine;
    using kc::tools::normalizeHash;
    using kc::tools::parseChecksumText;

    // ── 摘要算法：公开测试向量 ─────────────────────────────────────────────
    //   MD5("abc")    = 900150983cd24fb0d6963f7d28e17f72
    //   SHA-256("abc")= ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad
    const QByteArray abc = QByteArrayLiteral("abc");
    const QByteArray md5 = kc::crypto::hashBytes(abc, HashAlgo::Md5);
    const QByteArray sha = kc::crypto::hashBytes(abc, HashAlgo::Sha256);
    check(md5.toHex() == QByteArrayLiteral("900150983cd24fb0d6963f7d28e17f72"),
          "MD5(\"abc\") matches the published test vector");
    check(sha.toHex() == QByteArrayLiteral(
              "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"),
          "SHA-256(\"abc\") matches the published test vector");
    check(kc::crypto::hashAlgoLength(HashAlgo::Md5) == 16, "MD5 digest is 16 bytes");
    check(kc::crypto::hashAlgoLength(HashAlgo::Sha256) == 32, "SHA-256 digest is 32 bytes");
    check(kc::crypto::hashAlgoName(HashAlgo::Md5) == QStringLiteral("md5"),
          "algorithm name for file suffix is lowercase md5");

    // 空输入的摘要也要正确（空文件是合法输入，不能返回空串被当成失败）
    const QByteArray emptySha = kc::crypto::hashBytes(QByteArray(), HashAlgo::Sha256);
    check(emptySha.toHex() == QByteArrayLiteral(
              "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"),
          "SHA-256 of empty input is the well-known constant");

    // ── 流式文件摘要：跨块边界（1 MiB + 7 字节）必须与一次性摘要一致 ──────
    {
        QTemporaryDir dir;
        check(dir.isValid(), "temporary directory created");
        const QString path = QDir(dir.path()).filePath(QStringLiteral("firmware.img"));
        QByteArray payload;
        payload.reserve(1024 * 1024 + 7);
        for (int i = 0; i < 1024 * 1024 + 7; ++i)
            payload.append(static_cast<char>(i % 251));

        QFile file(path);
        check(file.open(QIODevice::WriteOnly), "temp firmware file opened for write");
        file.write(payload);
        file.close();

        QString error;
        const QString fileSha = kc::crypto::hashFile(path, HashAlgo::Sha256, &error);
        check(error.isEmpty(), "streaming hash reported no error");
        check(fileSha == QString::fromLatin1(
                              kc::crypto::hashBytes(payload, HashAlgo::Sha256).toHex()),
              "streaming hash equals one-shot hash across chunk boundaries");

        // 不存在的文件必须报错而不是返回空摘要当成功
        QString missingError;
        const QString missing = kc::crypto::hashFile(
            QDir(dir.path()).filePath(QStringLiteral("nope.bin")),
            HashAlgo::Sha256, &missingError);
        check(missing.isEmpty() && !missingError.isEmpty(),
              "missing file yields empty digest plus an error message");
    }

    // ── 校验文件格式 ───────────────────────────────────────────────────────
    check(formatChecksumLine(QStringLiteral("ABCDEF"), QStringLiteral("boot.img")) ==
              QStringLiteral("abcdef  boot.img"),
          "checksum line lowercases the hash and uses two spaces");
    check(formatChecksumLine(QStringLiteral("ab"), QStringLiteral("a\nb")) ==
              QStringLiteral("ab  ab"),
          "newlines are stripped from the file name");

    // coreutils 文本格式 / 二进制 `*` 标记 / CRLF / 注释 / 坏行
    const QByteArray text =
        "# generated by sha256sum\n"
        "900150983cd24fb0d6963f7d28e17f72  boot.img\n"
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad *super.img\r\n"
        "\n"
        "not-a-checksum  junk.bin\n"
        "deadbeef  too-short.bin\n";
    const auto records = parseChecksumText(text);
    check(records.size() == 2, "only well-formed lines are parsed");
    if (records.size() == 2) {
        check(records[0].hash == QStringLiteral("900150983cd24fb0d6963f7d28e17f72") &&
                  records[0].name == QStringLiteral("boot.img"),
              "text-mode line parsed with MD5 hash");
        check(records[1].hash.startsWith(QStringLiteral("ba7816bf")) &&
                  records[1].name == QStringLiteral("super.img"),
              "binary-mode line (hash + space + '*') parsed, CRLF stripped");
    }

    // 大小写混写的十六进制也要收，并统一成小写
    const auto upper = parseChecksumText(
        QByteArrayLiteral("BA7816BF8F01CFEA414140DE5DAE2223B00361A396177A9CB410FF61F20015AD  x.img\n"));
    check(upper.size() == 1 &&
              upper[0].hash == QStringLiteral("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"),
          "uppercase hash normalized to lowercase");

    // ── 校验文件命名 ───────────────────────────────────────────────────────
    check(checksumFileName(QStringLiteral("payload.bin"), HashAlgo::Sha256) ==
              QStringLiteral("payload.bin.sha256"),
          "single file gets a .sha256 suffix");
    check(checksumFileName(QString(), HashAlgo::Md5) == QStringLiteral("MD5SUMS"),
          "directory batch uses the coreutils MD5SUMS name");
    check(checksumFileName(QString(), HashAlgo::Sha256) == QStringLiteral("SHA256SUMS"),
          "directory batch uses the coreutils SHA256SUMS name");

    // ── normalizeHash（用户在「核对」里手输摘要时的容错）──────────────────
    check(normalizeHash(QStringLiteral(" 900150983CD24FB0D6963F7D28E17F72 "), HashAlgo::Md5) ==
              QStringLiteral("900150983cd24fb0d6963f7d28e17f72"),
          "normalizeHash trims spaces and lowercases");
    check(normalizeHash(QStringLiteral("900150983cd24fb0"), HashAlgo::Md5).isEmpty(),
          "wrong-length hash rejected");
    check(normalizeHash(QStringLiteral("zz0150983cd24fb0d6963f7d28e17f72"), HashAlgo::Md5).isEmpty(),
          "non-hex characters rejected");

    if (failures == 0) {
        std::cout << "checksum-tests: all checks passed\n";
        return 0;
    }
    std::cerr << "checksum-tests: " << failures << " check(s) failed\n";
    return 1;
}
